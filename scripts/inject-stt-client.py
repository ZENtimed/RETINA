# Copies the RETINA STT browser client (stt/client) into the Design System bundle.js, before the Screens block.
# Usage: python scripts/inject-stt-client.py <bundle.js> <stt/client dir>
# Re-running replaces the generated block, so the result is byte-identical for unchanged inputs.
import json, os, sys

BEGIN = '/* ---- STT client: generated by scripts/inject-stt-client.py from stt/client, do not hand-edit ---- */'
END = '/* ---- end STT client ---- */'
SCREENS = '/* ---- Screens:'
FILES = ['phrases.js', 'pcm.js', 'transcript-source.js', 'mic.js']


def read(path):
    return open(path, encoding='utf-8', newline='').read()


def main(bundle_path, client_dir):
    bundle = read(bundle_path)
    parts = [read(os.path.join(client_dir, f)).rstrip('\n') for f in FILES]
    worklet = read(os.path.join(client_dir, 'worklet.js'))
    block = '\n'.join([BEGIN] + parts + ['window.EMS.STT_WORKLET_SRC = ' + json.dumps(worklet) + ';', END]) + '\n'

    if BEGIN in bundle:
        start = bundle.index(BEGIN)
        stop = bundle.index(END, start) + len(END)
        if bundle[stop:stop + 1] == '\n':
            stop += 1
        bundle = bundle[:start] + block + bundle[stop:]
    else:
        at = bundle.find('\n' + SCREENS)
        if at < 0 and not bundle.startswith(SCREENS):
            print('no "' + SCREENS + '" line in ' + bundle_path, file=sys.stderr)
            return 1
        at = 0 if at < 0 else at + 1
        bundle = bundle[:at] + block + bundle[at:]

    open(bundle_path, 'w', encoding='utf-8', newline='\n').write(bundle)
    print('injected STT client into', bundle_path)
    return 0


if __name__ == '__main__':
    if len(sys.argv) != 3:
        print('usage: inject-stt-client.py <bundle.js> <stt/client dir>', file=sys.stderr)
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
