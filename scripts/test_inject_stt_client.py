import json, os, subprocess, sys, tempfile, unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, 'inject-stt-client.py')
BEGIN = '/* ---- STT client: generated by scripts/inject-stt-client.py from stt/client, do not hand-edit ---- */'
END = '/* ---- end STT client ---- */'
SCREENS = '/* ---- Screens: the five apps ---- */'
CLIENT = {'phrases.js': '/*phrases*/', 'pcm.js': '/*pcm*/', 'transcript-source.js': '/*ts*/', 'mic.js': '/*mic*/',
          'worklet.js': "registerProcessor('retina-pcm', X);\n"}


class InjectTest(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.mkdtemp()
        self.client = os.path.join(self.dir, 'client')
        os.makedirs(self.client)
        for name, body in CLIENT.items():
            open(os.path.join(self.client, name), 'w', encoding='utf-8', newline='\n').write(body)
        self.bundle = os.path.join(self.dir, 'bundle.js')

    def write_bundle(self, text):
        open(self.bundle, 'w', encoding='utf-8', newline='\n').write(text)

    def read_bundle(self):
        return open(self.bundle, encoding='utf-8', newline='').read()

    def run_script(self):
        return subprocess.run([sys.executable, SCRIPT, self.bundle, self.client], capture_output=True, text=True)

    def test_inserts_once_before_screens(self):
        self.write_bundle('/* components */\n' + SCREENS + '\n(function(){})();\n')
        self.assertEqual(self.run_script().returncode, 0)
        out = self.read_bundle()
        self.assertEqual(out.count(BEGIN), 1)
        self.assertEqual(out.count(END), 1)
        self.assertLess(out.index('/* components */'), out.index(BEGIN))
        self.assertLess(out.index(END), out.index(SCREENS))
        block = out[out.index(BEGIN):out.index(END)]
        for marker in ('/*phrases*/', '/*pcm*/', '/*ts*/', '/*mic*/'):
            self.assertIn(marker, block)
        self.assertLess(block.index('/*phrases*/'), block.index('/*ts*/'))

    def test_second_run_is_byte_identical(self):
        self.write_bundle('/* components */\n' + SCREENS + '\n')
        self.run_script()
        first = self.read_bundle()
        self.assertEqual(self.run_script().returncode, 0)
        self.assertEqual(self.read_bundle(), first)

    def test_worklet_is_a_json_string(self):
        self.write_bundle(SCREENS + '\n')
        self.run_script()
        expected = 'window.EMS.STT_WORKLET_SRC = ' + json.dumps(CLIENT['worklet.js']) + ';'
        self.assertIn(expected, self.read_bundle())

    def test_missing_screens_marker_fails_and_leaves_file(self):
        self.write_bundle('/* no marker */\n')
        result = self.run_script()
        self.assertEqual(result.returncode, 1)
        self.assertEqual(self.read_bundle(), '/* no marker */\n')


if __name__ == '__main__':
    unittest.main()
